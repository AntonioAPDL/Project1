sym <- function(M) 0.5 * (M + t(M))
safe_solve <- function(M) solve(sym(M))

reference_filter <- function(GG, m0, C0, ex_f, ex_q, FF, y, ex_df_mat, Ones, TT) {
  n <- length(m0)
  m <- matrix(0, n, TT)
  C <- array(0, c(n, n, TT))
  for (tt in seq_len(TT)) {
    if (tt == 1L) {
      a <- GG[, , tt] %*% m0
      P <- GG[, , tt] %*% C0 %*% t(GG[, , tt])
      R <- P + ex_df_mat * P
    } else {
      a <- GG[, , tt] %*% m[, tt - 1L]
      P <- GG[, , tt] %*% C[, , tt - 1L] %*% t(GG[, , tt])
      R <- P * ex_df_mat + P * Ones
    }
    R <- sym(R)
    f <- drop(t(FF[, , tt]) %*% a) + ex_f[, tt]
    q <- sym(t(FF[, , tt]) %*% R %*% FF[, , tt] + ex_q[, , tt])
    q_inv <- safe_solve(q)
    innov <- y[, tt] - f
    m[, tt] <- drop(a + R %*% FF[, , tt] %*% q_inv %*% innov)
    C[, , tt] <- sym(R - R %*% FF[, , tt] %*% q_inv %*% t(FF[, , tt]) %*% t(R))
  }
  list(fm = m, fC = C)
}

