max_slice_asymmetry <- function(x, n = NULL) {
  d <- dim(x)
  if (is.null(d) && !is.null(n) && length(x) == n * n) {
    x <- matrix(x, nrow = n, ncol = n)
    d <- dim(x)
  }
  if (length(d) == 2L) {
    return(max(abs(x - t(x))))
  }
  if (length(d) == 3L) {
    return(max(vapply(seq_len(d[3]), function(i) max(abs(x[, , i] - t(x[, , i]))), numeric(1))))
  }
  stop("expected matrix or 3D array for symmetry check", call. = FALSE)
}

